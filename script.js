(() => {
  "use strict";

  const letters = ["A", "B", "C", "D"];
  const quizPanel = document.querySelector("#quizPanel");
  const resultsPanel = document.querySelector("#resultsPanel");
  const progressText = document.querySelector("#progressText");
  const scoreText = document.querySelector("#scoreText");
  const progressFill = document.querySelector("#progressFill");
  const sourceNumber = document.querySelector("#sourceNumber");
  const questionText = document.querySelector("#questionText");
  const answers = document.querySelector("#answers");
  const feedback = document.querySelector("#feedback");
  const nextButton = document.querySelector("#nextButton");
  const finalScore = document.querySelector("#finalScore");
  const finalTotal = document.querySelector("#finalTotal");
  const finalPercent = document.querySelector("#finalPercent");
  const resultMessage = document.querySelector("#resultMessage");
  const rangeStart = document.querySelector("#rangeStart");
  const rangeEnd = document.querySelector("#rangeEnd");
  const rangeError = document.querySelector("#rangeError");

  let order = [];
  let current = 0;
  let score = 0;
  let answered = false;
  let activeStart = 1;
  let activeEnd = 100;

  function shuffled(items) {
    const copy = [...items];
    for (let i = copy.length - 1; i > 0; i -= 1) {
      const j = Math.floor(Math.random() * (i + 1));
      [copy[i], copy[j]] = [copy[j], copy[i]];
    }
    return copy;
  }

  function readRange() {
    const start = Number(rangeStart.value);
    const end = Number(rangeEnd.value);
    if (!Number.isInteger(start) || !Number.isInteger(end) || start < 1 || end > 100 || start > end) {
      rangeError.textContent = "Enter a valid range from 1 to 100. The first number must not be greater than the second.";
      rangeError.hidden = false;
      return null;
    }
    rangeError.hidden = true;
    return { start, end };
  }

  function startQuiz(useEnteredRange = false) {
    if (useEnteredRange) {
      const selected = readRange();
      if (!selected) return;
      activeStart = selected.start;
      activeEnd = selected.end;
    }
    const selectedQuestions = window.QUESTIONS.filter(
      (item) => item.number >= activeStart && item.number <= activeEnd,
    );
    order = shuffled(selectedQuestions);
    current = 0;
    score = 0;
    answered = false;
    resultsPanel.hidden = true;
    quizPanel.hidden = false;
    renderQuestion();
    window.scrollTo({ top: 0, behavior: "smooth" });
  }

  function renderQuestion() {
    const item = order[current];
    answered = false;
    progressText.textContent = `Question ${current + 1} of ${order.length}`;
    scoreText.textContent = `Score ${score}`;
    progressFill.style.width = `${((current + 1) / order.length) * 100}%`;
    sourceNumber.textContent = `Original question ${item.number}`;
    questionText.textContent = item.question;
    feedback.hidden = true;
    feedback.className = "feedback";
    nextButton.hidden = true;
    nextButton.textContent = current === order.length - 1 ? "See final score" : "Next question";
    answers.replaceChildren();

    item.options.forEach((option, index) => {
      const button = document.createElement("button");
      button.type = "button";
      button.className = "answer-button";
      button.dataset.index = String(index);
      button.innerHTML = `<span class="choice-letter">${letters[index]}</span><span></span>`;
      button.lastElementChild.textContent = option;
      button.addEventListener("click", () => chooseAnswer(index));
      answers.append(button);
    });
  }

  function chooseAnswer(index) {
    if (answered) return;
    answered = true;
    const item = order[current];
    const buttons = [...answers.querySelectorAll("button")];
    const isCorrect = index === item.correct;
    if (isCorrect) score += 1;

    buttons.forEach((button, buttonIndex) => {
      button.disabled = true;
      if (buttonIndex === item.correct) button.classList.add("correct");
      if (buttonIndex === index && !isCorrect) button.classList.add("wrong");
    });

    scoreText.textContent = `Score ${score}`;
    feedback.hidden = false;
    feedback.classList.add(isCorrect ? "correct" : "wrong");
    feedback.textContent = isCorrect
      ? "Correct!"
      : `Incorrect. The correct answer is ${letters[item.correct]}. ${item.options[item.correct]}`;
    nextButton.hidden = false;
    nextButton.focus({ preventScroll: true });
  }

  function advance() {
    if (!answered) return;
    if (current < order.length - 1) {
      current += 1;
      renderQuestion();
      questionText.focus?.();
      window.scrollTo({ top: 0, behavior: "smooth" });
      return;
    }
    showResults();
  }

  function showResults() {
    const percent = Math.round((score / order.length) * 100);
    quizPanel.hidden = true;
    resultsPanel.hidden = false;
    finalScore.textContent = String(score);
    finalTotal.textContent = String(order.length);
    finalPercent.textContent = `${percent}% correct`;
    resultMessage.textContent = percent >= 90
      ? "Excellent work. You have a strong command of the reviewer."
      : percent >= 75
        ? "Good result. Another shuffled round can help reinforce the questions you missed."
        : "Keep practicing. Each restart gives you a fresh question order.";
    resultsPanel.scrollIntoView({ behavior: "smooth", block: "start" });
  }

  nextButton.addEventListener("click", advance);
  document.querySelector("#applyRange").addEventListener("click", () => startQuiz(true));
  document.querySelector("#restartTop").addEventListener("click", () => startQuiz(false));
  document.querySelector("#restartResult").addEventListener("click", () => startQuiz(false));
  rangeEnd.addEventListener("keydown", (event) => {
    if (event.key === "Enter") startQuiz(true);
  });

  document.addEventListener("keydown", (event) => {
    if (!quizPanel.hidden && !answered && /^[1-4]$/.test(event.key)) {
      answers.querySelectorAll("button")[Number(event.key) - 1]?.click();
    } else if (!quizPanel.hidden && answered && event.key === "Enter") {
      advance();
    }
  });

  if (!Array.isArray(window.QUESTIONS) || window.QUESTIONS.length !== 100) {
    questionText.textContent = "The question set could not be loaded.";
    document.querySelector("#restartTop").disabled = true;
  } else {
    startQuiz();
  }
})();
